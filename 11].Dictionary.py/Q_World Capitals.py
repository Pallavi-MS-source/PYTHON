"""
Create a dictionary mapping 5 countries to their capital cities.Iterate through 
this dictionary using the items() method and print pair in the format
Country -> capital
"""
countries = { 'India':'Delhi','America':'Washington','iurhi':'uryui','eklsiw':'kedjo','hfjr':'jfejre'}
for country,capital in countries.items():
       print(f"{country} -> {capital}")
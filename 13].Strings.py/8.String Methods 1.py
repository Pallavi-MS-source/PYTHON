""" CASE COVERSION
# upper():converts all characters in string to uppercase
# lower():converts all characters in string to lowercase
# title():converts the first character of each word to uppercase n remaining to lowercase
# capitalize():coveerts only the first character of the entire string to uppercase
#               and rest to lower case
# swapcase():swap the case of each character """
text = "I am Coder"
print(text.upper())
print(text.lower())
print(text.title())
print(text.capitalize())
print(text.swapcase())